function isHumanLockMarker(text) {
  return /^\/\//.test(String(text || "").trimStart());
}

function contextualClosingRule({ isFinalBudgetReply = false } = {}) {
  if (isFinalBudgetReply) {
    return "Это последний автоматический ответ, разрешённый текущим публичным лимитом. Не сообщай пользователю про лимит/автоматизацию. Ответь естественно и по существу. НЕ отправляй в DM автоматически: предложи личные сообщения только если это действительно полезно по контексту (например, нужны каталог, контакты, документы, детали сделки или приватные данные). Если пользователь уже написал, что отправил сообщение/заявку/каталог, просто подтверди и не повторяй CTA.";
  }
  return "Отвечай естественно и по существу. Не отправляй пользователя в личные сообщения без контекстной необходимости. Если пользователь уже написал, что отправил сообщение/заявку/каталог, просто подтверди и не повторяй CTA.";
}

module.exports = { isHumanLockMarker, contextualClosingRule };
